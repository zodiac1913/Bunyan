/**
 * Aggregated catalog of all documented data-* tags in SML docs.
 * Builds from each component's `attributes` array so the list stays in sync.
 * @returns {Object} data-tag inventory with usage metadata
 * @static
 */
static getDataTagsCatalog() {
  const namespace = this.getNamespace();
  const tagMap = new Map();

  for (const component of namespace.classes || []) {
    this.collectComponentDataTags(component, tagMap);
  }

  const tags = this.finalizeDataTagCatalog(tagMap);

  return {
    namespace: namespace?.namespace || "SML",
    generatedFrom: "SmlDocSml component attributes",
    totalTags: tags.length,
    tags
  };
}

static collectComponentDataTags(component, tagMap) {
  const methodName = component?.name;
  const doc = this.getComponentDoc(methodName);
  if (!doc) return;

  const className = doc?.class || methodName;
  const attributes = Array.isArray(doc?.attributes) ? doc.attributes : [];
  for (const attr of attributes) {
    const tagName = this.normalizeDataTagName(attr?.name);
    if (!tagName) continue;
    this.mergeDataTagUsage(tagMap, tagName, className, attr);
  }
}

static getComponentDoc(methodName) {
  if (!methodName || typeof this[methodName] !== "function") return null;
  try {
    return this[methodName]();
  } catch (err) {
    console.warn("SmlDocSml.getDataTagsCatalog: could not load doc for", methodName, err);
    return null;
  }
}

static normalizeDataTagName(rawName) {
  const tagName = (rawName || "").toString().trim();
  return tagName.startsWith("data-") ? tagName : "";
}

static ensureDataTagBucket(tagMap, tagName) {
  if (!tagMap.has(tagName)) {
    tagMap.set(tagName, {
      name: tagName,
      usedBy: [],
      purposes: new Set(),
      requiredBy: [],
      deprecatedIn: []
    });
  }
  return tagMap.get(tagName);
}

static mergeDataTagUsage(tagMap, tagName, className, attr) {
  const bucket = this.ensureDataTagBucket(tagMap, tagName);
  const description = attr?.description || "";

  bucket.usedBy.push({
    class: className,
    type: attr?.type || "string",
    required: attr?.required === true,
    default: Object.hasOwn(attr || {}, "default") ? attr.default : undefined,
    purpose: description
  });

  if (description) bucket.purposes.add(description);
  if (attr?.required === true) bucket.requiredBy.push(className);
  if (attr?.deprecated === true) bucket.deprecatedIn.push(className);
}

static finalizeDataTagCatalog(tagMap) {
  return Array.from(tagMap.values())
    .map((tag) => ({
      name: tag.name,
      purpose: Array.from(tag.purposes),
      usedBy: tag.usedBy,
      requiredBy: Array.from(new Set(tag.requiredBy)).sort((a, b) => a.localeCompare(b)),
      deprecatedIn: Array.from(new Set(tag.deprecatedIn)).sort((a, b) => a.localeCompare(b))
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

